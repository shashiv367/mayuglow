export function getProductBySlug(slug) {
  return products.find((p) => p.slug === slug)
}

export function getProductById(id) {
  return products.find((p) => p.id === id)
}

export function getFeaturedProducts() {
  return products.filter((p) => p.featured)
}

export function getBestsellers() {
  return products.filter((p) => p.bestseller)
}

export function getProductsByCategory(category) {
  if (category === 'all') return products
  if (category === 'bestseller') return products.filter((p) => p.bestseller)
  if (category === 'new') return products.filter((p) => p.new)
  return products.filter((p) => p.category === category)
}

export function getRelatedProducts(product, limit = 4) {
  return products
    .filter((p) => p.id !== product.id && (p.category === product.category || p.flavors.some((f) => product.flavors.includes(f))))
    .slice(0, limit)
}

